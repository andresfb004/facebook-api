        <h1 id="introduction">Introduction</h1>
<p>API REST tipo Facebook construida con Laravel: publicaciones con imágenes, comentarios, likes por usuario, búsqueda y autenticación con Sanctum.</p>
<aside>
    <strong>Base URL</strong>: <code>http://127.0.0.1:8000</code>
</aside>
<pre><code>Esta documentación describe cada endpoint de la API: método, URL, parámetros, body y respuestas posibles.

La API está versionada: la **v1** (`/api/v1`) es la versión estable y la **v2** (`/api/v2`) está en desarrollo, con un nuevo formato de respuesta para las publicaciones.

&lt;aside&gt;A la derecha (o debajo, en el celular) verás ejemplos de cada petición en bash y JavaScript. Con el botón &lt;b&gt;Try it out&lt;/b&gt; puedes probar los endpoints desde el navegador.&lt;/aside&gt;</code></pre>

        <h1 id="authenticating-requests">Authenticating requests</h1>
<p>To authenticate requests, include an <strong><code>Authorization</code></strong> header with the value <strong><code>"Bearer {TU_TOKEN}"</code></strong>.</p>
<p>All authenticated endpoints are marked with a <code>requires authentication</code> badge in the documentation below.</p>
<p>Obtén el token con <code>POST /api/v1/register</code> o <code>POST /api/v1/login</code> y envíalo en el header <code>Authorization: Bearer {TU_TOKEN}</code>.</p>

        <h1 id="autenticacion">Autenticación</h1>

    <p>Registro, inicio y cierre de sesión. Los endpoints protegidos de la API
requieren el token que devuelven el registro o el login.</p>

